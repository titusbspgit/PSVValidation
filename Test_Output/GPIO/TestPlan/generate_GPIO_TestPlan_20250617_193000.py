def push_to_github(file_path):
    """Push the generated XLSX file to GitHub."""
    if not GITHUB_TOKEN:
        print("ERROR: GITHUB_TOKEN environment variable not set.")
        print("Set it with: export GITHUB_TOKEN=your_token_here")
        sys.exit(1)

    # Read the file as binary and base64 encode
    with open(file_path, "rb") as f:
        content_bytes = f.read()
    content_b64 = base64.b64encode(content_bytes).decode("utf-8")

    # Check if file already exists (to get SHA for update)
    api_url = f"https://api.github.com/repos/{OWNER}/{REPO}/contents/{OUTPUT_PATH}"
    headers = {
        "Authorization": f"token {GITHUB_TOKEN}",
        "Accept": "application/vnd.github.v3+json",
    }

    sha = None
    resp = requests.get(api_url, headers=headers)
    if resp.status_code == 200:
        sha = resp.json().get("sha")

    # Create or update file
    payload = {
        "message": COMMIT_MSG,
        "content": content_b64,
        "branch": BRANCH,
    }
    if sha:
        payload["sha"] = sha

    resp = requests.put(api_url, headers=headers, json=payload)
    if resp.status_code in (200, 201):
        result = resp.json()
        commit_sha = result.get("commit", {}).get("sha", "unknown")
        html_url = result.get("content", {}).get("html_url", "unknown")
        print(f"SUCCESS: File pushed to GitHub")
        print(f"  Commit SHA: {commit_sha}")
        print(f"  GitHub URL: {html_url}")
        return commit_sha, html_url
    else:
        print(f"ERROR: GitHub API returned {resp.status_code}")
        print(resp.text)
        sys.exit(1)


