def save_and_get_bytes(wb):
    buffer = BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer.read()


def push_to_github(file_bytes, filepath):
    try:
        from github import Github
    except ImportError:
        print("WARNING: PyGithub not installed. Run: pip install PyGithub")
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, "wb") as f:
            f.write(file_bytes)
        print(f"File saved locally: {filepath}")
        return False

    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        print("WARNING: GITHUB_TOKEN not set. Saving locally.")
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, "wb") as f:
            f.write(file_bytes)
        print(f"File saved locally: {filepath}")
        return False

    g = Github(token)
    repo = g.get_repo(f"{GITHUB_OWNER}/{GITHUB_REPO}")

    try:
        existing = repo.get_contents(filepath, ref=GITHUB_BRANCH)
        result = repo.update_file(
            path=filepath,
            message=f"Update {FILENAME} - GPIO TestPlan Excel (28-col, 10 rows)",
            content=file_bytes,
            sha=existing.sha,
            branch=GITHUB_BRANCH
        )
    except Exception:
        result = repo.create_file(
            path=filepath,
            message=f"Add {FILENAME} - GPIO TestPlan Excel (28-col, 10 rows)",
            content=file_bytes,
            branch=GITHUB_BRANCH
        )

    commit_sha = result['commit'].sha
    print(f"Pushed to GitHub. Commit: {commit_sha}")
    return True


